export const STAGE_LABEL: Record<BatchStage, string> = {
  weaving: "Weaving",
  printing: "Printing",
  cutting: "Cutting",
  packaging: "Packaging",
};

/** What each stage takes in — used in labels and empty states. */
export function stageInputLabel(kind: LineKind, stage: BatchStage) {
  const unit = UNIT_LABEL[kind];
  const upstream = UPSTREAM_STAGE[kind][stage];
  if (!upstream) return `planned ${unit}`;
  const noun = upstream === "printing" ? "printed" : upstream === "weaving" ? "woven" : "cut";
  return `${noun} ${unit}`;
}

export const UPSTREAM_STAGE: Record<LineKind, Record<BatchStage, BatchStage | null>> = {
  printed: { weaving: null, printing: null, cutting: "printing", packaging: "cutting" },
  woven: { weaving: null, printing: null, cutting: "weaving", packaging: "cutting" },
};

export function isFirstStage(kind: LineKind, stage: BatchStage) {
  return STAGES_OF[kind][0] === stage;
}

/** A batch is editable only before it finishes. */
export function isBatchOpen(status: BatchStatus) {
  return status !== "COMPLETED" && status !== "CANCELLED";
}
