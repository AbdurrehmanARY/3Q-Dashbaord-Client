/** Batch-based production: the material-flow model. Decimals arrive as strings. */

export type BatchStage = "weaving" | "printing" | "cutting" | "packaging";

/**
 * Which workflow a line runs. The two share a batch lifecycle and differ in two places:
 * their first stage, and what they count.
 *
 *   printed   Printing -> Cutting -> Packaging, in ROLLS
 *   woven     Weaving  -> Cutting -> Packaging, in PIECES
 */
export type LineKind = "printed" | "woven";

export const STAGES_OF: Record<LineKind, BatchStage[]> = {
  printed: ["printing", "cutting", "packaging"],
  woven: ["weaving", "cutting", "packaging"],
};

/** What the figures are counting, for labels and units on screen. */
export const UNIT_LABEL: Record<LineKind, string> = { printed: "rolls", woven: "pcs" };

export type BatchStatus = "PLANNED" | "ASSIGNED" | "IN_PROGRESS" | "COMPLETED" | "CANCELLED";

/** One edge: this batch took `rolls` from `sourceBatchCode`. */
export interface BatchSourceEdge {
  sourceBatchId: number;
  sourceBatchCode: string;
  rolls: number;
}

export interface ProductionBatch {
  id: number;
  /**
   * The line this batch belongs to when it is a PRINTED label type. Since migration 0025 every
   * batch carries exactly one of the two line columns — which one is set says whether the batch
   * counts rolls (printed) or pieces (woven).
   */
  productionOrderLineId: number | null;
  /** The line this batch belongs to when it is a WOVEN label type — the other workflow's column. */
  wovenProductionLineId: number | null;
  labelType?: string | null;
  stage: BatchStage;
  batchNumber: number;
  /** P-001, C-001, PK-001 */
  batchCode: string;
  machineId: number | null;
  machineName: string | null;
    operatorId: number | null;
  operatorName: string | null;
  /** Which planned size a weaving batch weaves — present on Size Label batches only. */
  labelSize?: string | null;
  /** Input reserved for this batch. */
  assignedRolls: string;
  /** Good output made so far. */
  producedRolls: string;
  /** Scrapped input — recordable at any stage (printing, weaving, cutting, packaging). */
  wastedRolls: string;
  /** Reason for scrapped material. NULL if none recorded. */
  wasteReason: string | null;
  /** How much of this batch's output downstream has taken. */
  consumedRolls: string;
  /** produced − consumed. Generated by the database. */
  availableRolls: string;
  packagedQty: string;
  status: BatchStatus;
  notes: string | null;
  startedAt: string | null;
  completedAt: string | null;
  createdAt: string;
  updatedAt: string;
  sources: BatchSourceEdge[];
  /**
   * How long this batch should take, in minutes. Only weaving has a known formula so far;
   * every other stage comes back as 0 and renders as `00:00` until its formula is added.
   */
  estimatedMinutes: number;
}

/** Minutes as `HH:MM`, the format the floor reads on a job ticket. */
export function formatDuration(minutes: number): string {
  const safe = Math.max(0, Math.round(Number(minutes) || 0));
  return `${String(Math.floor(safe / 60)).padStart(2, "0")}:${String(safe % 60).padStart(2, "0")}`;
}

